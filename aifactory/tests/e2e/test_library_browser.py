"""First start creates a seeded library after reviewing its plan, with no external calls."""

from __future__ import annotations

import json
from pathlib import Path

import pytest
from f3_repo import api_get, git, make_f3_repo, obs_server
from multi_repo_e2e import diagnostic_tripwire
from playwright.sync_api import Dialog, Route, expect, sync_playwright
from test_f3_browser import _launch

pytestmark = [pytest.mark.browser, pytest.mark.xdist_group("e2e")]


def test_library_seed_browser(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.delenv("HAIFA_LIBRARY", raising=False)
    monkeypatch.setenv("GIT_CONFIG_COUNT", "1")
    monkeypatch.setenv("GIT_CONFIG_KEY_0", "commit.gpgsign")
    monkeypatch.setenv("GIT_CONFIG_VALUE_0", "false")
    script = tmp_path / "fake.json"
    script.write_text(json.dumps({"agents": {}}), encoding="utf-8")
    wire, marker = diagnostic_tripwire(tmp_path)
    home = tmp_path / "haifa-home"
    external: list[str] = []
    dialogs: list[str] = []
    with obs_server(None, script, wire, tmp_path / "obs.log", home) as server:
        with sync_playwright() as playwright:
            browser = _launch(playwright)
            context = browser.new_context(base_url=server.url, service_workers="block")
            context.set_default_timeout(60_000)
            expect.set_options(timeout=60_000)

            def local_only(route: Route) -> None:
                if not route.request.url.startswith(server.url + "/"):
                    external.append(route.request.url)
                    route.abort()
                elif "/api/machine/check" in route.request.url:
                    # Real machine probes, explicitly offline even on an authenticated machine.
                    query = "&" if "?" in route.request.url else "?"
                    route.continue_(url=route.request.url + query + "offline=1")
                else:
                    route.continue_()

            context.route("**/*", local_only)
            page = context.new_page()

            def dismiss(dialog: Dialog) -> None:
                dialogs.append(dialog.message)
                dialog.dismiss()

            page.on("dialog", dismiss)
            try:
                page.goto("/")
                expect(page).to_have_url(f"{server.url}/#/overview")
                page.locator('[data-test="readiness-warning"]').click()
                expect(page).to_have_url(f"{server.url}/#/problems")
                page.locator(
                    '[data-test="readiness-warning"] a[href="#/setup/library"]'
                ).first.click()
                expect(page).to_have_url(f"{server.url}/#/setup/library")
                expect(page.locator("h1")).to_have_text("Knihovna")
                page.locator('[data-test="library-init"]').click()
                modal = page.locator('[data-test="confirm-dialog"]')
                expect(modal).to_contain_text("Založit knihovnu ze semínka")
                expect(modal).to_contain_text("agent/builder")
                expect(modal).to_contain_text("skill/factory")  # generated by factory --skill
                assert not (home / "library").exists()
                modal.locator('[data-test="confirm-ok"]').click()
                expect(page.locator('[data-test="library-path"]')).to_have_text(
                    str(home / "library")
                )
                assert git(home / "library", "rev-list", "--count", "HEAD") == "1"
                # the library is a section of this machine; the topbar chip leads to it
                page.locator('[data-test="library-chip-ok"]').click()
                expect(page).to_have_url(f"{server.url}/#/setup/library")
                expect(page.locator("h1")).to_have_text("Knihovna")
                expect(page.locator('[data-test="library-items"]')).to_contain_text("builder")
                expect(page.locator('[data-test="library-items"]')).to_contain_text("v1 ·")
                page.locator(
                    '[data-test="library-item"] button:has(.item-name:text-is("builder"))'
                ).click()
                expect(page.locator('[data-test="library-detail"]')).to_contain_text("system.md")
                expect(page.locator('[data-test="item-history"]')).to_contain_text("v1 ·")
                expect(page.locator('[data-test="item-no-overrides"]')).to_be_visible()
                page.locator('[data-test="tab-workflow"]').click()
                expect(page.locator('[data-test="library-item"]').first).to_be_visible()
                expect(page.locator('[data-test="library-items"]')).to_contain_text(
                    "plan-build-test-quality"
                )
                page.locator('[data-test="tab-skill"]').click()
                expect(page.locator('[data-test="library-items"]')).to_contain_text("factory")
                page.locator('[data-test="tab-extension"]').click()
                expect(page.locator('[data-test="library-items"]')).to_contain_text("subagents")
                expect(page.locator('[data-test="library-sync-state"]')).to_contain_text(
                    "Bez remote"
                )
                page.locator('[data-test="library-reseed"]').click()
                expect(modal.locator('[data-test="seed-nothing"]')).to_be_visible()
                modal.locator('[data-test="confirm-cancel"]').click()
                assert git(home / "library", "rev-list", "--count", "HEAD") == "1"
                assert api_get(server.url, "/api/library")["exists"]
                assert api_get(server.url, "/api/repos")["repos"] == []
                assert not marker.exists()
                assert external == [] and dialogs == []
            finally:
                context.close()
                browser.close()


def test_repo_library_hide_restore_browser(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.delenv("HAIFA_LIBRARY", raising=False)
    script = tmp_path / "fake.json"
    script.write_text(json.dumps({"agents": {}}), encoding="utf-8")
    wire, marker = diagnostic_tripwire(tmp_path)
    home = tmp_path / "haifa-home"
    repo = make_f3_repo(tmp_path / "repo")
    workflows = repo / ".factory/workflows"
    (workflows / "haifa-implement-task.yaml").write_text(
        "name: repo-only\nsteps: []\n", encoding="utf-8"
    )
    with obs_server(repo, script, wire, tmp_path / "obs.log", home) as server:
        with sync_playwright() as playwright:
            browser = _launch(playwright)
            context = browser.new_context(base_url=server.url, service_workers="block")
            context.set_default_timeout(30_000)
            page = context.new_page()

            def offline(route: Route) -> None:
                if "/api/machine/check" in route.request.url:
                    query = "&" if "?" in route.request.url else "?"
                    route.continue_(url=route.request.url + query + "offline=1")
                else:
                    route.continue_()

            context.route("**/*", offline)
            try:
                page.goto("/#/setup/library")
                page.locator('[data-test="tab-workflow"]').click()
                row = page.locator('[data-test="inventory-item"]').filter(
                    has_text="haifa-implement-task"
                )
                expect(row).to_contain_text("Pouze v repu")
                row.locator("button").first.click()
                expect(page.locator('[data-test="inventory-detail"]')).to_contain_text(
                    "haifa-implement-task.yaml"
                )
                row.locator('[data-test="inventory-hide"]').click()
                expect(row).to_have_count(0)
                page.reload()
                page.locator('[data-test="tab-workflow"]').click()
                expect(row).to_have_count(0)
                page.locator('[data-test="inventory-ignored"]').check()
                expect(row).to_contain_text("Ignorováno")
                page.locator('[data-test="ignore-restore"]').click()
                page.locator('[data-test="inventory-ignored"]').uncheck()
                expect(row).to_have_count(1)
                assert (workflows / "haifa-implement-task.yaml").exists()
                assert not marker.exists()
            finally:
                context.close()
                browser.close()
